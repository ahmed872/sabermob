parts: list[tuple[str, str]] = []
questions: list[tuple[int, str, str]] = []


def part(title, sub):
    parts.append((title, sub))


def q(question, html):
    questions.append((len(parts) - 1, question, html))


def fig(img, cap, half=False):
    cls = ' class="half"' if half else ''
    return f'<figure{cls}><img src="img/{img}" alt=""><figcaption>{cap}</figcaption></figure>'


def grid(*figs):
    return '<div class="grid2">' + ''.join(figs) + '</div>'


def box(kind, title, body):
    return f'<div class="box {kind}"><span class="t">{title}</span>{body}</div>'


def steps(*xs):
    return '<ol class="steps">' + ''.join(f'<li>{x}</li>' for x in xs) + '</ol>'


def ul(*xs):
    return '<ul>' + ''.join(f'<li>{x}</li>' for x in xs) + '</ul>'


def path(x):
    return f'<span class="path">{x}</span>'


def keys(*rows):
    return '<table><tr><th>المفتاح</th><th>الوظيفة</th></tr>' + ''.join(f'<tr><td>{k}</td><td>{v}</td></tr>' for k, v in rows) + '</table>'


def table(head, rows, first_width='30%'):
    h = f'<tr><th style="width:{first_width}">{head[0]}</th><th>{head[1]}</th></tr>'
    return '<table>' + h + ''.join(f'<tr><td>{a}</td><td>{b}</td></tr>' for a, b in rows) + '</table>'


